import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const load = async path => import('data:text/javascript;base64,' + Buffer.from(await readFile(new URL(path, import.meta.url), 'utf8')).toString('base64'));
const { storeListing, discoveryCartItem, filterListings } = await load('../mobile/src/utils/discovery.js');
const shop = { id: 'shop', ownerId: 'seller', name: 'Local shop', city: 'Łódź', businessType: 'FASHION' };
const product = { id: 'product', name: 'Jacket', price: 90, currency: 'PLN', stockQuantity: 2 };
const mapped = storeListing(shop, product);
assert.equal(mapped.id, 'shop:shop:product');
assert.equal(mapped.sellerId, 'seller');
assert.equal(mapped.listingType, 'FASHION');
assert.deepEqual(mapped.mediaUrls, []);
assert.equal(discoveryCartItem(mapped).id, 'product');
assert.equal(discoveryCartItem(mapped).kind, 'product');
assert.equal(discoveryCartItem(mapped).shopId, 'shop');
assert.equal(discoveryCartItem({ id: 'listing' }).kind, 'listing');
const sold = storeListing(shop, { ...product, id: 'sold', stockQuantity: 0 });
assert.equal(sold.status, 'SOLD');
assert.deepEqual(filterListings([mapped, sold], { city: 'lodz', query: 'jacket', category: 'FASHION' }), [mapped]);
assert.deepEqual(filterListings([mapped], { category: 'FOOD' }), []);
assert.deepEqual(filterListings([mapped, { ...mapped, id: 'cheaper', price: 40 }], { sort: 'price-low' }).map(i => i.id), ['cheaper', mapped.id]);
console.log('PASS store product mapping, real cart identifiers, missing imagery, out-of-stock filtering, accent-insensitive search and price sorting');
